import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import { writeFileSync } from 'node:fs';
import { createApplication } from '../../server/app.js';
import { hashPassword } from '../../server/identity/policy.js';
import { testDatabase } from '../helpers.js';
test('布局前后真实HTTP/数据库契约：组织选择、账号重置、额度目标及拒绝', async ({ page }) => {
  test.skip(!process.env.TEST_DATABASE_URL, 'Requires dedicated disposable database');
  const { pool } = await testDatabase();
  const platform = randomUUID(); const account = randomUUID();
  const password = 'Layout34FixturePwd!';
  const hash = await hashPassword(password);
  await pool.query("INSERT INTO organizations(id,name,kind) VALUES($1,'平台34','platform')", [platform]);
  await pool.query(`INSERT INTO accounts(id,organization_id,email,password_hash,role,must_change) VALUES($1,$2,'platform34@example.com',$3,'platform',false)`, [account, platform, hash]);
  const origin = 'http://127.0.0.1:3334';
  const app = await createApplication(pool, origin, false, undefined, undefined, undefined, undefined, undefined, undefined, undefined, undefined, undefined, resolve(process.env.ISSUE34_BASELINE ? '.scratch/issue34-baseline-web' : 'dist/web'));
  await app.listen(3334, '127.0.0.1');
  const posts: { path: string; body: Record<string, unknown> }[] = [];
  page.on('request', req => { if (req.method() === 'POST') posts.push({ path: new URL(req.url()).pathname, body: req.postDataJSON() }); });
  const api = (path: string, body?: Record<string, unknown>) => page.evaluate(async ({ path, body }) => {
    const csrf = document.cookie.split('; ').find(s => s.startsWith('identity_csrf='))?.slice(14) ?? '';
    const res = await fetch('/api/' + path, body ? { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf }, body: JSON.stringify(body) } : undefined);
    return { status: res.status, data: await res.json() };
  }, { path, body });
  try {
    await page.goto(origin + '/platform/organizations');
    await page.getByLabel('登录账号', { exact: true }).fill('platform34@example.com');
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await expect(page.locator('.account-name')).toHaveText('platform34@example.com');
    const created = await api('organizations', { name: '目标企业34', kind: 'terminal', countryCode: '+65', phone: '81233456', email: 'child34@example.com', requestId: randomUUID() });
    expect(created.status).toBe(201);
    await page.goto(origin + '/platform/organizations');
    const list = (await api('organizations')).data.children;
    const child = list.find((item: any) => item.email === 'child34@example.com');
    expect(child.id).not.toBe(child.accountId); expect(child.id).not.toBe(account);
    await page.getByRole('link', { name: '下级详情', exact: true }).click();
    await page.getByRole('button', { name: '停用组织', exact: true }).click();
    await expect(page.getByRole('button', { name: '恢复组织', exact: true })).toBeVisible();
    expect(posts.find(p => p.path === '/api/organizations/state')?.body).toEqual({ organizationId: child.id, active: false });
    expect((await pool.query('SELECT active FROM organizations WHERE id=$1', [child.id])).rows[0].active).toBe(false);
    await page.getByRole('button', { name: '恢复组织', exact: true }).click();
    await page.getByRole('button', { name: '重置管理员密码', exact: true }).click();
    await expect(page.getByRole('heading', { name: '管理员密码重置成功' })).toBeVisible();
    expect(posts.find(p => p.path === '/api/password-resets')?.body).toEqual({ accountId: child.accountId, requestId: expect.any(String) });
    await page.getByRole('button', { name: '已保存，关闭凭据' }).click();
    await page.goto(origin + '/platform/settings/email-quota');
    await page.locator('.el-select').click(); await page.getByRole('option', { name: '目标企业34' }).click();
    await page.locator('input[type=number]').fill('2345');
    await page.getByRole('button', { name: '保存日额度' }).click();
    await expect(page.getByRole('status').filter({ hasText: '2345' })).toBeVisible();
    expect(posts.find(p => p.path === '/api/email-quota/configure')?.body).toEqual({ organizationId: child.id, dailyLimit: 2345 });
    expect((await pool.query('SELECT daily_limit FROM organization_email_limits WHERE organization_id=$1', [child.id])).rows[0].daily_limit).toBe(2345);
    const denied = await api('email-quota/configure', { organizationId: child.id, dailyLimit: 0 }); expect(denied.status).toBe(400);
    const wrongTarget = await api('organizations/state', { organizationId: child.accountId, active: false }); expect(wrongTarget.status).toBe(403);
    const resetWrongTarget = await api('password-resets', { accountId: child.id, requestId: randomUUID() }); expect(resetWrongTarget.status).toBe(403);
    await pool.query(`INSERT INTO accounts(id,organization_id,email,password_hash,role,must_change) VALUES($1,$2,'sales34@example.com',$3,'sales',false)`, [randomUUID(), child.id, hash]);
    await api('auth/logout', {});
    await page.goto(origin + '/help');
    await page.getByLabel('登录账号', { exact: true }).fill('sales34@example.com'); await page.getByLabel('密码', { exact: true }).fill(password); await page.getByRole('button', { name: '登录', exact: true }).click();
    await expect(page.locator('.account-name')).toHaveText('sales34@example.com');
    expect((await api('email-quota/configure', { organizationId: child.id, dailyLimit: 9999 })).status).toBe(403);
    await page.goto(origin + '/platform/settings/email-quota'); await expect(page).not.toHaveURL(origin + '/platform/settings/email-quota');
    await page.goto(origin + '/account/settings');
    await page.getByLabel('当前密码', { exact: true }).fill(password);
    await page.getByLabel('新密码', { exact: true }).fill('Layout34ChangedPwd!');
    await page.getByLabel('确认新密码', { exact: true }).fill('Layout34ChangedPwd!');
    await page.getByRole('button', { name: '确认修改并重新登录' }).click();
    await expect(page.getByLabel('登录账号', { exact: true })).toBeVisible();
    expect(posts.find(p => p.path === '/api/auth/password')?.body).toEqual({ currentPassword: password, newPassword: 'Layout34ChangedPwd!', confirmPassword: 'Layout34ChangedPwd!' });
    expect((await api('auth/login', { email: 'sales34@example.com', password })).status).toBe(401);
    expect((await api('auth/login', { email: 'sales34@example.com', password: 'Layout34ChangedPwd!' })).status).toBe(200);
    const baseline = process.env.ISSUE34_BASELINE ? 'before' : 'after';
    writeFileSync(`.scratch/issue34-contract-${baseline}.json`, JSON.stringify({ baseline, ids: { platform, account, organization: child.id, administrator: child.accountId }, requests: posts.filter(p => ['/api/organizations/state', '/api/password-resets', '/api/email-quota/configure'].includes(p.path)), result: { limit: 2345, invalidLimit: denied.status, wrongOrganizationIdentifier: wrongTarget.status, wrongAccountIdentifier: resetWrongTarget.status, salesDenied: 403 } }, null, 2));
  } finally { await app.close(); await pool.end(); }
});
