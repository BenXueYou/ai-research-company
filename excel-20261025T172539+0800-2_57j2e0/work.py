def _rows(ws):
    out = []
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row, min_col=1, max_col=4, values_only=True):
        out.append(tuple('' if v is None else str(v) for v in row))
    return out


def _nonempty(v):
    return v is not None and str(v).strip() != ''


def check_r1(values_wb, formulas_wb):
    if values_wb.sheetnames != ['功能清单']:
        return False
    ws = values_wb['功能清单']
    if ws.max_column != 4:
        return False
    rows = _rows(ws)
    if len(rows) != EXPECTED_TOTAL:
        return False
    # 无人日/金额/优先级等额外内容混入
    banned = ['人日', '万元', '¥', '报价']
    for r in rows:
        for v in r:
            for b in banned:
                if b in v:
                    return False
    return True


def check_r2(values_wb, formulas_wb):
    ws = values_wb['功能清单']
    got_headers = [ws.cell(row=1, column=c).value for c in range(1, 5)]
    if got_headers != HEADERS:
        return False
    rows = _rows(ws)
    if len(rows) != len(DATA):
        return False
    for got, exp in zip(rows, DATA):
        if tuple(x.strip() for x in got) != tuple(x.strip() for x in exp):
            return False
        for v in got:
            if not _nonempty(v):
                return False
    return True


def check_r3(values_wb, formulas_wb):
    rows = _rows(values_wb['功能清单'])
    if len(rows) != EXPECTED_TOTAL:
        return False
    names = [r[2] for r in rows]
    if len(set(names)) != len(names):
        return False
    l1 = [r[0] for r in rows]
    if set(l1) != set(EXPECTED_L1):
        return False
    # 同一一级模块必须连续
    seen, prev = set(), None
    for v in l1:
        if v != prev:
            if v in seen:
                return False
            seen.add(v)
            prev = v
    # 同一二级模块必须连续，且其一级模块唯一
    seen2, prev2 = set(), None
    for a, b in zip(l1, [r[1] for r in rows]):
        key = (a, b)
        if key != prev2:
            if key in seen2:
                return False
            seen2.add(key)
            prev2 = key
    # 与既定结构逐组核对行数
    from collections import Counter
    got_c = Counter((r[0], r[1]) for r in rows)
    exp_c = Counter((d[0], d[1]) for d in DATA)
    return got_c == exp_c


